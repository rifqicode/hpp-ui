export default async function verifyProductUx(page, baseUrl = 'http://localhost:5173') {
  const checks = [];
  const main = page.getByRole('main');
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  const assertWidth = async () => page.evaluate(() => {
    const main = document.querySelector('main');
    const root = main.firstElementChild;
    const style = getComputedStyle(main);
    const available = main.clientWidth - parseFloat(style.paddingLeft) - parseFloat(style.paddingRight);
    return { width: innerWidth, full: Math.abs(root.getBoundingClientRect().width - available) < 2, overflow: main.scrollWidth > main.clientWidth || document.documentElement.scrollWidth > innerWidth };
  });
  await page.setViewportSize({ width: 1920, height: 1080 });
  await page.goto(`${baseUrl}/production/products`);
  const table = page.getByRole('table', { name: 'Tabel produk' });
  await table.waitFor();
  assert((await assertWidth()).full, 'Catalog does not use the available width');
  await table.getByRole('button', { name: 'Lihat varian', exact: true }).click();
  await table.getByText('LAT-LRG', { exact: true }).waitFor();
  await table.getByRole('button', { name: 'Tutup varian', exact: true }).click();
  await page.getByRole('button', { name: 'Rugi 1', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('table tbody').querySelectorAll('tr:not([hidden])').length === 1);
  await page.getByRole('button', { name: 'Total produk 3', exact: true }).click();
  await page.getByRole('button', { name: /Urutkan:/ }).click();
  await page.getByRole('menuitem', { name: 'Harga tertinggi', exact: true }).click();
  await page.getByRole('button', { name: 'Urutkan: Harga tertinggi' }).waitFor();
  await page.getByRole('textbox', { name: 'Cari produk', exact: true }).fill('tidak-ada-hasil');
  await page.getByRole('heading', { name: 'Tidak ada produk yang cocok' }).waitFor();
  await page.getByRole('button', { name: 'Reset filter', exact: true }).first().click();
  await table.waitFor();
  await page.getByRole('button', { name: 'Tampilan kartu', exact: true }).click();
  await page.getByRole('article').first().waitFor();
  await page.getByRole('button', { name: 'Tampilan tabel', exact: true }).click();
  await table.waitFor();
  checks.push('Catalog expansion, loss shortcut, sort, search, empty state and view controls work');

  await page.getByRole('button', { name: 'Kategori', exact: true }).click();
  await page.getByLabel('Nama kategori', { exact: true }).fill('Musiman');
  await page.getByRole('button', { name: 'Tambah kategori', exact: true }).click();
  await main.getByText('Musiman', { exact: true }).waitFor();
  assert((await assertWidth()).full, 'Categories do not use the available width');
  await page.getByRole('button', { name: 'Master Add on', exact: true }).click();
  await main.getByRole('heading', { name: 'Extra Shot', exact: true }).waitFor();
  assert((await assertWidth()).full, 'Add-ons do not use the available width');
  await page.getByRole('button', { name: 'Edit grup', exact: true }).click();
  await page.getByRole('dialog').getByLabel('Harga tambahan (Rp)', { exact: true }).fill('6000');
  assert(await page.getByRole('dialog').getByLabel('Harga tambahan (Rp)', { exact: true }).inputValue() === '6.000', 'Add-on price is not formatted');
  await page.getByRole('dialog').getByRole('button', { name: 'Batal', exact: true }).click();
  await page.getByRole('button', { name: 'Arsipkan', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Batal', exact: true }).click();
  checks.push('Category creation and full-width hubs work; modifier editing and archive dialogs can be cancelled');

  await page.getByRole('button', { name: 'Daftar Produk', exact: true }).click();
  await page.getByRole('button', { name: 'Tambah Produk', exact: true }).click();
  await page.getByRole('button', { name: 'Lanjut', exact: true }).click();
  assert(await page.getByLabel('Nama produk', { exact: true }).evaluate(e => e === document.activeElement), 'Invalid product name did not receive focus');
  await page.getByLabel('Nama produk', { exact: true }).fill('Latte Uji Layout');
  await page.getByLabel('Cara menyiapkan produk', { exact: true }).selectOption('MAKE_TO_ORDER');
  await page.getByLabel('Deskripsi', { exact: true }).fill('Data pengujian layout, bukan transaksi toko.');
  await page.getByRole('button', { name: 'Buat kategori', exact: true }).click();
  await page.getByLabel('Nama kategori baru', { exact: true }).fill('Uji form');
  await page.getByRole('button', { name: 'Tambah kategori', exact: true }).click();
  await page.getByRole('button', { name: 'Lanjut', exact: true }).click();
  await page.getByLabel('Satuan hasil', { exact: true }).fill('cup');
  await page.getByRole('button', { name: 'Tambah bahan', exact: true }).click();
  await page.getByLabel('Bahan 1', { exact: true }).selectOption('coffee');
  await page.getByLabel('Takaran (g)', { exact: true }).fill('15');
  await page.getByLabel('Harga jual (Rp)', { exact: true }).fill('18000');
  await page.getByRole('button', { name: 'Bantu tentukan harga', exact: true }).click();
  await page.getByLabel('Tambahan harga (%)', { exact: true }).fill('60');
  await page.getByRole('complementary', { name: 'Estimasi varian' }).getByText(/Tercapai berdasarkan biaya bahan/).waitFor();
  await page.getByRole('button', { name: 'Tambah varian', exact: true }).click();
  await page.getByLabel('Nama varian', { exact: true }).fill('Large');
  await page.getByLabel('Salin resep dari varian lain', { exact: true }).selectOption('0');
  await page.getByLabel('Takaran (g)', { exact: true }).fill('20');
  await page.getByLabel('Harga jual (Rp)', { exact: true }).fill('25000');
  await page.getByLabel('Salin resep dari varian lain', { exact: true }).selectOption('0');
  await page.getByRole('dialog', { name: 'Ganti resep Large?' }).getByRole('button', { name: 'Batal', exact: true }).click();
  assert(await page.getByLabel('Takaran (g)', { exact: true }).inputValue() === '20', 'Cancelling recipe copy changed the quantity');
  await page.getByRole('button', { name: 'Lanjut', exact: true }).click();
  await page.getByRole('checkbox', { name: /Extra Shot/ }).check();
  await page.getByRole('heading', { name: 'Periksa sebelum menyimpan' }).waitFor();
  await page.getByRole('button', { name: 'Simpan produk', exact: true }).click();
  await page.waitForURL('**/production/products/created-product');
  await main.getByRole('heading', { name: 'Resep Regular', exact: true }).waitFor();
  assert((await assertWidth()).full, 'Product detail does not use the available width');
  await page.getByRole('button', { name: 'Edit harga & resep', exact: true }).click();
  assert(await page.getByLabel('Harga jual (Rp)', { exact: true }).inputValue() === '18.000', 'Quick edit did not open the selected variant price');
  assert((await assertWidth()).full, 'Product edit does not use the available width');
  await page.getByRole('button', { name: 'Batal', exact: true }).click();
  checks.push('MTO create, inline category, focused validation, numeric formats, recipe copy, target feedback, review summary and quick edit work');

  await page.getByRole('link', { name: 'Kembali ke produk', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  const firstCard = await page.getByRole('article').first().boundingBox();
  assert(firstCard && firstCard.y < 610, 'Mobile products are buried below the controls');
  await page.getByRole('button', { name: 'Filter', exact: true }).click();
  await page.getByLabel('Kategori produk', { exact: true }).selectOption('Coffee');
  await page.waitForFunction(() => document.querySelectorAll('article').length === 1);
  await page.getByRole('button', { name: 'Reset filter', exact: true }).click();
  const sort = await page.getByRole('button', { name: /Urutkan:/ }).boundingBox();
  assert(sort && sort.width > 140, 'Mobile sort control is too narrow');
  await page.screenshot({ path: 'artifacts/product-ux-list-mobile.png' });
  await page.getByRole('button', { name: 'Tambah Produk', exact: true }).click();
  await page.getByLabel('Nama produk', { exact: true }).fill('Draft Mobile');
  await page.getByRole('button', { name: 'Batal', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Keluar dari form', exact: true }).click();
  await page.getByRole('button', { name: 'Tambah Produk', exact: true }).click();
  assert(await page.getByLabel('Nama produk', { exact: true }).inputValue() === 'Draft Mobile', 'Create draft was not restored');
  await page.getByRole('button', { name: 'Batal', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Buang draft & keluar', exact: true }).click();
  await page.getByRole('button', { name: 'Tambah Produk', exact: true }).click();
  assert(await page.getByLabel('Nama produk', { exact: true }).inputValue() === '', 'Discarded draft was restored');
  const sizes = [];
  for (const width of [320, 390, 768, 1024, 1440, 1920]) {
    await page.setViewportSize({ width, height: 900 });
    const size = await assertWidth(); sizes.push(size);
    assert(size.full && !size.overflow, `Create layout failed at ${width}px`);
  }
  await page.screenshot({ path: 'artifacts/product-ux-create-desktop.png' });
  await page.evaluate(() => document.documentElement.classList.add('dark'));
  await page.waitForTimeout(200);
  assert(await page.evaluate(() => getComputedStyle(document.body).backgroundColor !== 'rgb(255, 255, 255)'), 'Existing dark theme tokens were dropped from the build');
  await page.screenshot({ path: 'artifacts/product-ux-create-dark.png' });
  await page.evaluate(() => document.documentElement.classList.remove('dark'));
  await page.waitForTimeout(200);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'artifacts/product-ux-create-mobile.png' });
  checks.push('Mobile filters, readable sort, draft restore/discard, six viewport widths and existing dark theme work');
  return { checks, sizes, mobileCardTop: firstCard.y };
}
