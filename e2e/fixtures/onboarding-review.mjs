async (page) => {
  page.removeAllListeners('dialog');
  page.on('dialog', dialog => dialog.accept());
  const root = '/home/rifqicode/project/hpp/hpp-ui/dist';
  const checks = [];
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.unrouteAll({ behavior: 'wait' });
  await page.route('https://curo.local/**', route => {
    const path = new URL(route.request().url()).pathname;
    return route.fulfill({ path: root + (path.startsWith('/assets/') ? path : '/index.html') });
  });
  const stocks = [], products = [], operations = new Map();
  let state = null;
  let materialWrites = 0, productWrites = 0;
  const ensureState = () => state ??= { id: 'onboarding-1', store_id: 'store-1', status: 'IN_PROGRESS', step: 1, revision: 0, draft: {}, product_id: null };
  const response = (extra = {}) => ({ state, should_start: !state, dismissed: state?.status === 'SKIPPED', ...extra });
  await page.route('**/api/**', async route => {
    const request = route.request();
    const path = new URL(request.url()).pathname.split('/api')[1];
    const method = request.method();
    let data = [];
    let status = 200;
    if (path === '/onboarding') {
      if (method === 'PUT') {
        const input = request.postDataJSON(); ensureState();
        if (input.revision !== state.revision) status = 409;
        else state = { ...state, step: input.step, draft: input.draft, revision: state.revision + 1, status: input.action === 'complete' ? 'COMPLETED' : input.action === 'skip' ? 'SKIPPED' : 'IN_PROGRESS' };
      }
      data = response({ product: products.find(p => p.id === state?.product_id) });
    } else if (path === '/onboarding/materials') {
      const input = request.postDataJSON(); ensureState();
      let stock = operations.get(input.operation_key);
      if (!stock) {
        materialWrites++;
        stock = { id: input.stock_id || `stock-${stocks.length + 1}`, name: input.name, base_unit: input.base_unit, current_stock: '0', cost_per_unit: String(Number(input.price) / Number(input.package_quantity)), reference_unit_cost: String(Number(input.price) / Number(input.package_quantity)) };
        const index = stocks.findIndex(s => s.id === stock.id);
        if (index < 0) stocks.push(stock); else stocks[index] = stock;
        operations.set(input.operation_key, stock); state.revision++;
      }
      data = response({ stock });
    } else if (path === '/onboarding/product') {
      const input = request.postDataJSON(); ensureState();
      if ('yield' in input) throw new Error('Onboarding product payload still contains batch yield');
      let product = operations.get(input.operation_key);
      if (!product) {
        productWrites++;
        const payload = input.product;
        const variants = payload.variants.map((variant, index) => {
          const ingredients = variant.ingredients.map((line, i) => {
            const stock = stocks.find(s => s.id === line.stock_id);
            const quantity = Number(line.quantity);
            return { id: `line-${index}-${i}`, stock_id: stock.id, stock_name: stock.name, base_unit: stock.base_unit, quantity, unit_cost: stock.cost_per_unit, subtotal_cost: quantity * Number(stock.cost_per_unit), available_stock: '0' };
          });
          return { ...variant, id: variant.id || `variant-${index}`, product_id: 'product-1', sku: variant.sku || `ONB-${index}`, current_stock: '0', latest_hpp: '0', estimated_hpp: ingredients.reduce((sum, i) => sum + i.subtotal_cost, 0), ingredients, batches: [] };
        });
        product = { ...payload, id: 'product-1', category: payload.category || 'Tanpa Kategori', created_at: '2026-10-24T00:00:00Z', variants, modifier_groups: [] };
        const index = products.findIndex(p => p.id === product.id);
        if (index < 0) products.push(product); else products[index] = product;
        operations.set(input.operation_key, product); state.revision++; state.product_id = product.id; state.step = 4;
      }
      data = response({ product });
    } else if (path === '/stocks') data = { items: stocks, total_pages: 1 };
    else if (path === '/products') data = { items: products, total_pages: 1 };
    else if (path === '/stores') data = [{ id: 'store-1', name: 'Toko Uji Onboarding' }];
    else if (path === '/permissions/me') data = { permissions: ['menu:dashboard', 'stocks:read', 'stocks:create', 'products:read', 'products:write'], role: 'OWNER' };
    else if (path === '/subscription/usage') data = { tier: 'FREE', status: 'ACTIVE', quotas: {}, features: {} };
    else if (path === '/dashboard/overview') data = {};
    await route.fulfill({ status, contentType: 'application/json', headers: { 'access-control-allow-origin': 'https://curo.local', 'access-control-allow-credentials': 'true', 'access-control-allow-headers': 'Content-Type,Authorization,X-Store-ID', 'access-control-allow-methods': 'GET,POST,PUT,OPTIONS' }, body: JSON.stringify({ success: status === 200, message: status === 409 ? 'Onboarding changed on another device' : 'OK', data }) });
  });
  await page.addInitScript(() => {
    localStorage.setItem('token', 'onboarding-review');
    localStorage.setItem('auth-storage', JSON.stringify({ version: 0, state: { user: { id: 'owner-1', name: 'Penguji', email: 'test@example.invalid', account_type: 'OWNER', role: 'OWNER' }, token: 'onboarding-review', activeStoreId: 'store-1', activeStoreName: 'Toko Uji Onboarding' } }));
  });
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  const checkWidth = async () => assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Page overflows horizontally');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('https://curo.local/onboarding');
  await page.getByRole('heading', { name: 'Kenali biaya di balik produk Anda' }).waitFor();
  assert(await page.getByText('Lihat contoh hitung HPP', { exact: true }).count() === 0, 'Removed example is still visible');
  assert(stocks.length === 0 && products.length === 0, 'Introduction wrote operational data');
  await checkWidth();
  await page.screenshot({ path: '/home/rifqicode/project/hpp/artifacts/onboarding-intro-desktop.png', fullPage: true });
  checks.push('Introduction shows the app flow without an example calculator or operational writes');
  await page.getByRole('button', { name: 'Lanjut: isi bahan baku' }).click();
  await page.getByRole('img', { name: 'Kenali HPP, selesai', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Tambah bahan baku', exact: true }).click();
  await page.getByRole('button', { name: 'Hapus bahan 2' }).click();
  await page.getByLabel('Nama bahan', { exact: true }).fill('Tepung');
  await page.getByLabel('Jumlah bahan (g)', { exact: true }).fill('1000');
  await page.getByLabel('Harga total (Rp)', { exact: true }).fill('20000');
  await page.getByText('Harga satuan: Rp20 / g', { exact: true }).waitFor();
  const addMaterialButton = page.getByRole('button', { name: 'Tambah bahan baku', exact: true });
  assert(await addMaterialButton.getAttribute('data-variant') === 'default', 'Add material button does not use the app primary theme');
  await page.setViewportSize({ width: 360, height: 800 });
  await checkWidth();
  await page.screenshot({ path: '/home/rifqicode/project/hpp/artifacts/onboarding-material-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Simpan bahan & lanjut' }).click();
  await page.getByLabel('Nama produk', { exact: true }).fill('Roti Uji');
  await page.getByRole('img', { name: 'Bahan baku, selesai', exact: true }).waitFor();
  await page.getByLabel('Cara menyiapkan produk', { exact: true }).selectOption('MAKE_TO_STOCK');
  await page.getByRole('button', { name: 'Lanjut', exact: true }).click();
  assert(await page.getByLabel('Jumlah hasil satu resep', { exact: true }).count() === 0, 'Onboarding still has a batch-yield input');
  await page.getByRole('heading', { name: 'Resep per satu pcs', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Tambah bahan', exact: true }).click();
  await page.getByLabel('Bahan 1', { exact: true }).selectOption('stock-1');
  await page.getByLabel('Takaran (g)', { exact: true }).fill('100');
  await page.getByRole('button', { name: 'Tambah bahan', exact: true }).click();
  const deleteIngredient = page.getByRole('button', { name: 'Hapus bahan 2', exact: true });
  assert((await deleteIngredient.textContent()).trim() === '', 'Delete ingredient still renders text');
  await deleteIngredient.click();
  await page.getByRole('button', { name: 'Bantu tentukan harga', exact: true }).click();
  await page.getByLabel('Tambahan harga (%)', { exact: true }).click();
  await page.getByLabel('Tambahan harga (%)', { exact: true }).pressSequentially('100');
  assert(await page.getByLabel('Tambahan harga (%)', { exact: true }).inputValue() === '100', 'Typed margin gained extra digits: ' + await page.getByLabel('Tambahan harga (%)', { exact: true }).inputValue());
  assert(await page.getByLabel('Tambahan harga (%)', { exact: true }).getAttribute('aria-invalid') === 'false', '100 percent cost-based target is still rejected');
  assert(await page.getByLabel('Harga jual (Rp)', { exact: true }).inputValue() === '0', 'Calculator changed the selling price before approval');
  await page.getByRole('button', { name: 'Pakai hasil perhitungan', exact: true }).click();
  assert(await page.getByLabel('Harga jual (Rp)', { exact: true }).inputValue() === '4.000', '100 percent target does not double ingredient cost');
  await page.getByLabel('Tambahan harga (%)', { exact: true }).fill('150');
  assert(await page.getByLabel('Harga jual (Rp)', { exact: true }).inputValue() === '4.000', 'Changing the percentage overwrote the accepted price');
  await page.getByRole('button', { name: 'Pakai hasil perhitungan', exact: true }).click();
  assert(await page.getByLabel('Harga jual (Rp)', { exact: true }).inputValue() === '5.000', 'Regular price does not follow target margin');
  assert(await page.getByLabel('Harga jual (Rp)', { exact: true }).getAttribute('readonly') === null, 'Selling price must allow manual edits');
  assert(await page.getByRole('button', { name: 'Tambah bahan', exact: true }).getAttribute('data-variant') === 'default', 'Add ingredient does not use the primary theme');
  await page.getByRole('button', { name: 'Tambah varian', exact: true }).click();
  await page.getByLabel('Nama varian', { exact: true }).fill('Large');
  await page.getByLabel('Salin resep dari varian lain', { exact: true }).selectOption('0');
  await page.getByLabel('Takaran (g)', { exact: true }).fill('150');
  await page.getByLabel('Tambahan harga (%)', { exact: true }).fill('100');
  await page.getByRole('button', { name: 'Pakai hasil perhitungan', exact: true }).click();
  assert(await page.getByLabel('Harga jual (Rp)', { exact: true }).inputValue() === '6.000', 'Large price does not follow its own target margin');
  assert(await page.getByRole('button', { name: 'Tambah bahan yang belum ada', exact: true }).getAttribute('data-variant') === 'default', 'Add missing material does not use the primary theme');
  await page.getByRole('button', { name: 'Tambah bahan yang belum ada' }).click();
  await page.getByLabel('Harga total (Rp)', { exact: true }).fill('25000');
  await page.getByText('Harga satuan: Rp25 / g', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Simpan bahan & lanjut' }).click();
  assert(await page.getByLabel('Nama varian', { exact: true }).inputValue() === 'Large', 'Selected variant was lost when adding material');
  assert(await page.getByLabel('Takaran (g)', { exact: true }).inputValue() === '150', 'Variant recipe draft was lost');
  assert(await page.getByLabel('Harga jual (Rp)', { exact: true }).inputValue() === '6.000', 'Updating material cost overwrote the accepted price');
  await page.getByRole('button', { name: 'Bantu tentukan harga', exact: true }).click();
  await page.getByRole('button', { name: 'Pakai hasil perhitungan', exact: true }).click();
  assert(await page.getByLabel('Harga jual (Rp)', { exact: true }).inputValue() === '7.500', 'Accepted suggestion was not applied');
  await checkWidth();
  await page.screenshot({ path: '/home/rifqicode/project/hpp/artifacts/onboarding-recipe-mobile.png', fullPage: true });
  for (const width of [768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 1000 });
    await checkWidth();
  }
  await page.waitForFunction(() => document.querySelector('[aria-label="Estimasi varian"]').innerText.includes('3.750'));
  await page.screenshot({ path: '/home/rifqicode/project/hpp/artifacts/onboarding-recipe-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 360, height: 800 });
  await page.reload();
  await page.getByLabel('Nama varian', { exact: true }).waitFor();
  await page.getByRole('button', { name: /Info dasar/ }).click();
  assert(await page.getByLabel('Nama produk', { exact: true }).inputValue() === 'Roti Uji', 'Server draft did not resume after navigation');
  await page.getByRole('button', { name: 'Lanjut', exact: true }).click();
  await page.getByRole('img', { name: 'Bahan baku, selesai', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Simpan produk', exact: true }).click();
  await page.getByRole('heading', { name: 'Ini biaya produk Anda' }).waitFor();
  await page.getByRole('img', { name: 'Produk & resep, selesai', exact: true }).waitFor();
  assert(stocks.length === 1 && stocks[0].current_stock === '0', 'Reference cost created phantom stock or a duplicate material');
  assert(products[0].variants[0].ingredients[0].quantity === 100, 'Per-unit quantity was changed');
  assert(products[0].variants[1].ingredients[0].quantity === 150, 'Large variant lost its separate recipe');
  assert(products[0].variants[0].selling_price === 5000 && products[0].variants[1].selling_price === 7500, 'Applying a suggestion overwrote another variant price');
  assert(products[0].variants[0].estimated_hpp === 2500, 'Per-unit recipe or updated material cost was ignored');
  await page.getByRole('button', { name: 'Large', exact: true }).click();
  assert(await page.getByLabel('Coba harga jual varian (Rp)').count() === 0, 'Removed result-price input is still present');
  await page.getByText('50%', { exact: true }).waitFor();
  assert(productWrites === 1, 'Viewing another variant changed the saved product');
  await checkWidth();
  await page.screenshot({ path: '/home/rifqicode/project/hpp/artifacts/onboarding-result-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 768, height: 1024 });
  await checkWidth();
  await page.screenshot({ path: '/home/rifqicode/project/hpp/artifacts/onboarding-result-tablet.png', fullPage: true });
  await page.getByRole('button', { name: 'Kembali', exact: true }).focus();
  await page.keyboard.press('Tab');
  await page.waitForFunction(() => document.activeElement.textContent.includes('Selesai & buka dashboard') && document.activeElement.matches(':focus-visible') && getComputedStyle(document.activeElement).outlineColor === 'rgb(80, 72, 229)');
  checks.push('Keyboard navigation reaches completion with a visible purple focus outline');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.evaluate(() => document.documentElement.classList.add('dark'));
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.text-primary')).color === 'rgb(165, 180, 252)');
  await checkWidth();
  await page.screenshot({ path: '/home/rifqicode/project/hpp/artifacts/onboarding-result-dark.png', fullPage: true });
  await page.evaluate(() => document.documentElement.classList.remove('dark'));
  await page.getByRole('button', { name: 'Kembali', exact: true }).click();
  await page.getByRole('button', { name: /Info dasar/ }).click();
  await page.getByLabel('Nama produk', { exact: true }).fill('Roti Uji Revisi');
  await page.getByRole('button', { name: 'Lanjut', exact: true }).click();
  await page.getByRole('button', { name: 'Simpan produk', exact: true }).click();
  await page.getByRole('heading', { name: 'Roti Uji Revisi', exact: true }).waitFor();
  assert(products.length === 1, 'Editing the onboarding product created a duplicate');
  await page.getByRole('button', { name: 'Selesai & buka dashboard' }).click();
  await page.waitForURL('**/dashboard');
  assert(state.status === 'COMPLETED', 'Completion status was not persisted');
  assert(await page.getByRole('region', { name: 'Panduan mulai', exact: true }).count() === 0, 'Completed owner still sees the onboarding invitation');
  await page.reload();
  await page.waitForURL('**/dashboard');
  assert(await page.getByRole('region', { name: 'Panduan mulai', exact: true }).count() === 0, 'Completed owner sees the invitation again after reload');
  await page.goto('https://curo.local/onboarding');
  await page.getByRole('heading', { name: 'Ini biaya produk Anda' }).waitFor();
  await page.getByRole('button', { name: 'Lewati', exact: true }).click();
  await page.waitForURL('**/dashboard');
  assert(state.status === 'SKIPPED', 'Skip status was not persisted');
  assert(await page.getByRole('region', { name: 'Panduan mulai', exact: true }).count() === 0, 'Skipped owner still sees an onboarding invitation');
  await page.goto('https://curo.local/onboarding');
  await page.waitForURL('**/dashboard');
  assert(products.length === 1 && stocks.length === 1, 'Skipping changed saved operational data');
  checks.push('Lewati dismisses onboarding, hides the dashboard invitation and prevents reopening after reload');
  checks.push('Shared product builder, targets of 100 percent and above, separate variant recipes/prices, material correction, draft resume, existing HPP results, product correction and completion work');
  checks.push('No horizontal overflow at 360px, 768px, 1024px or 1440px; light and dark screenshots captured');
  const result = { checks, materialWrites, productWrites, errors, artifacts: ['onboarding-intro-desktop.png', 'onboarding-material-mobile.png', 'onboarding-recipe-mobile.png', 'onboarding-recipe-desktop.png', 'onboarding-result-mobile.png', 'onboarding-result-tablet.png', 'onboarding-result-dark.png'] };
  console.log(JSON.stringify(result));
  await page.evaluate(value => { window.__onboardingReview = value; }, result);
  return result;
}
