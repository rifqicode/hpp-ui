import { expect, test } from '@playwright/test'
import { agreementDocument } from '../tests/support/agreement-fixture'

test.describe('Registration agreement', () => {
  test.beforeEach(async ({ page }) => {
    await page.route('**/auth/service-agreement', route => route.fulfill({
      json: { success: true, data: agreementDocument },
    }))
  })
  test('requires scrolling the document and explicit consent before continuing', async ({ page }) => {
    await page.goto('/register')
    const next = page.getByRole('button', { name: 'Lanjut ke Profil Toko' })
    const consent = page.getByRole('checkbox')
    await expect(next).toBeDisabled()
    await expect(consent).toBeDisabled()

    await page.getByLabel(/Nama Lengkap Pemilik/).fill('Pemilik Toko')
    await page.getByLabel(/Alamat Email Bisnis/).fill('pemilik@example.com')
    await page.getByLabel(/^Kata Sandi/).fill('Abcdef12!')
    await page.getByLabel(/Konfirmasi Kata Sandi/).fill('Abcdef12!')
    await expect(next).toBeDisabled()

    const open = page.getByRole('button', { name: 'Baca Ketentuan Layanan & Kebijakan Privasi' })
    await open.click()
    const document = page.getByRole('region', { name: 'Dokumen Ketentuan Layanan dan Kebijakan Privasi' })
    await expect(document).toBeFocused()
    await expect(page.getByRole('button', { name: 'Selesai membaca dan setuju' })).toBeDisabled()
    await document.press('PageDown')
    await expect(page.getByRole('button', { name: 'Selesai membaca dan setuju' })).toBeDisabled()
    await page.keyboard.press('Escape')
    await expect(consent).toBeDisabled()
    await expect(open).toBeFocused()

    await open.click()
    await document.press('End')
    const finish = page.getByRole('button', { name: 'Selesai membaca dan setuju' })
    await expect(finish).toBeEnabled()
    await finish.click()
    await expect(consent).toBeEnabled()
    await expect(consent).toBeChecked()
    await expect(next).toBeEnabled()
    await consent.uncheck()
    await expect(next).toBeDisabled()
    await consent.check()
    await next.click()
    await expect(page.getByRole('heading', { name: 'Setup Profil Toko Pertama' })).toBeVisible()
    await expect(page.getByText('Mata Uang Finansial:')).toHaveCount(0)
    await expect(page.getByLabel(/Catatan Singkat Usaha/)).toHaveCount(0)
    await page.getByRole('button', { name: 'Kembali', exact: true }).click()
    await expect(consent).toBeChecked()
    await expect(next).toBeEnabled()
    await page.reload()
    await expect(consent).toBeDisabled()
    await expect(consent).not.toBeChecked()
  })

  test('keeps the document and footer usable on a narrow screen', async ({ page }) => {
    await page.setViewportSize({ width: 360, height: 640 })
    await page.goto('/register')
    await page.getByRole('button', { name: /Baca Ketentuan/ }).click()
    const dialog = page.getByRole('dialog')
    const document = page.getByRole('region', { name: 'Dokumen Ketentuan Layanan dan Kebijakan Privasi' })
    await expect(dialog).toBeVisible()
    expect(await page.evaluate(() => window.document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    const bounds = await dialog.boundingBox()
    expect(bounds!.y).toBeGreaterThanOrEqual(0)
    expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(640)
    await expect(page.getByRole('button', { name: 'Selesai membaca dan setuju' })).toBeInViewport()
    await document.evaluate((element) => element.scrollTo(0, element.scrollHeight))
    await expect(page.getByRole('button', { name: 'Selesai membaca dan setuju' })).toBeEnabled()
    await page.screenshot({ path: 'artifacts/registration-agreement-mobile.png' })
    await page.getByRole('button', { name: 'Selesai membaca dan setuju' }).click()
    await expect(page.getByRole('checkbox')).toBeEnabled()
    await expect(page.getByRole('checkbox')).toBeChecked()
  })
})
