import { fireEvent, render, screen } from '@testing-library/react';
import { beforeEach, describe, expect, it, vi } from 'vitest';
import { DragScrollArea } from '@/components/ui/drag-scroll-area';

beforeEach(() => {
  vi.stubGlobal(
    'PointerEvent',
    class extends MouseEvent {
      readonly pointerId: number;
      readonly pointerType: string;
      constructor(type: string, options: PointerEventInit = {}) {
        super(type, options);
        this.pointerId = options.pointerId ?? 1;
        this.pointerType = options.pointerType ?? 'mouse';
      }
    },
  );
});

function setup(children = <span>Area kosong</span>) {
  const clicked = vi.fn();
  render(
    <DragScrollArea aria-label="Pembelian" onClick={clicked}>
      {children}
    </DragScrollArea>,
  );
  const area = screen.getByRole('region', { name: 'Pembelian' });
  Object.defineProperties(area, {
    clientWidth: { configurable: true, value: 300 },
    scrollWidth: { configurable: true, value: 900 },
    clientHeight: { value: 200 },
  });
  const captured = new Set<number>();
  area.setPointerCapture = vi.fn(id => {
    captured.add(id);
  });
  area.hasPointerCapture = vi.fn(id => captured.has(id));
  area.releasePointerCapture = vi.fn(id => {
    captured.delete(id);
  });
  return { area, clicked };
}

const pointer = { pointerId: 1, pointerType: 'mouse', button: 0, clientX: 200, clientY: 40 };

describe('DragScrollArea', () => {
  it('pans horizontally, captures movement, and blocks the click generated by dragging', () => {
    const { area, clicked } = setup();
    area.scrollLeft = 20;
    fireEvent.pointerDown(screen.getByText('Area kosong'), pointer);
    fireEvent.pointerMove(area, { ...pointer, clientX: 197 });
    expect(area.scrollLeft).toBe(20);
    fireEvent.pointerMove(area, { ...pointer, clientX: 80 });
    expect(area.scrollLeft).toBe(140);
    expect(area).toHaveAttribute('data-dragging', 'true');
    fireEvent.pointerUp(area, { ...pointer, clientX: 80 });
    expect(area.releasePointerCapture).toHaveBeenCalledWith(1);
    expect(area).not.toHaveAttribute('data-dragging');
    fireEvent.click(area, { detail: 1 });
    expect(clicked).not.toHaveBeenCalled();
    fireEvent.pointerDown(area, pointer);
    fireEvent.pointerUp(area, pointer);
    fireEvent.click(area, { detail: 1 });
    expect(clicked).toHaveBeenCalledOnce();
  });

  it.each([
    <button>
      <span>Target</span>
    </button>,
    <a href="#detail">Target</a>,
    <input aria-label="Target" />,
    <div draggable>Target</div>,
    <div draggable={false}>Target</div>,
  ])('leaves controls and Kanban cards to their own interactions (%#)', child => {
    const { area } = setup(child);
    const target = screen.queryByText('Target') ?? screen.getByLabelText('Target');
    fireEvent.pointerDown(target, pointer);
    fireEvent.pointerMove(area, { ...pointer, clientX: 80 });
    expect(area.setPointerCapture).not.toHaveBeenCalled();
    expect(area.scrollLeft).toBe(0);
  });

  it.each([{ pointerType: 'touch' }, { pointerType: 'pen' }, { button: 2 }])(
    'preserves native gestures for %o',
    options => {
      const { area } = setup();
      fireEvent.pointerDown(area, { ...pointer, ...options });
      fireEvent.pointerMove(area, { ...pointer, ...options, clientX: 80 });
      expect(area.setPointerCapture).not.toHaveBeenCalled();
      expect(area.scrollLeft).toBe(0);
    },
  );

  it.each(['pointerCancel', 'lostPointerCapture'] as const)('clears a gesture after %s', event => {
    const { area } = setup();
    fireEvent.pointerDown(area, pointer);
    fireEvent.pointerMove(area, { ...pointer, clientX: 100 });
    expect(area).toHaveAttribute('data-dragging', 'true');
    fireEvent[event](area, pointer);
    fireEvent.pointerMove(area, { ...pointer, clientX: 50 });
    expect(area.scrollLeft).toBe(100);
    expect(area).not.toHaveAttribute('data-dragging');
  });

  it('does not capture a fitting area or a press on the native scrollbar', () => {
    const { area } = setup();
    fireEvent.pointerDown(area, { ...pointer, clientY: 201 });
    Object.defineProperty(area, 'scrollWidth', { value: 300 });
    fireEvent.pointerDown(area, pointer);
    expect(area.setPointerCapture).not.toHaveBeenCalled();
  });
});
